package com.mossymeadows.game;

import android.os.Handler;
import android.os.Looper;

import androidx.annotation.NonNull;

import com.google.android.gms.ads.AdError;
import com.google.android.gms.ads.AdRequest;
import com.google.android.gms.ads.FullScreenContentCallback;
import com.google.android.gms.ads.LoadAdError;
import com.google.android.gms.ads.MobileAds;
import com.google.android.gms.ads.interstitial.InterstitialAd;
import com.google.android.gms.ads.interstitial.InterstitialAdLoadCallback;
import com.google.android.gms.ads.rewarded.RewardedAd;
import com.google.android.gms.ads.rewarded.RewardedAdLoadCallback;
import com.google.android.ump.ConsentInformation;
import com.google.android.ump.ConsentRequestParameters;
import com.google.android.ump.UserMessagingPlatform;

import java.util.concurrent.atomic.AtomicBoolean;

/**
 * Google AdMob ads for the game (compiled only in the Gradle "AdMob" build).
 *
 * - Consent first: the Google UMP form (GDPR / US states) is shown when required,
 *   ads are only requested once consent allows it.
 * - One rewarded ad and one interstitial are kept preloaded; failed loads retry
 *   with a growing delay so we never hammer the network.
 * - Ad unit ids come from string resources generated by Gradle (Google's test
 *   ids by default — replace them with your own before publishing).
 */
public class AdMobBackend implements AdsBackend {
    private final MainActivity activity;
    private final Handler main = new Handler(Looper.getMainLooper());
    private final AtomicBoolean started = new AtomicBoolean(false);
    private final ConsentInformation consent;
    private volatile boolean initialized = false;
    private RewardedAd rewarded;
    private InterstitialAd interstitial;
    private boolean loadingRewarded, loadingInterstitial;
    private long retryRewarded = 15_000, retryInterstitial = 15_000;

    public AdMobBackend(MainActivity activity) {
        this.activity = activity;
        consent = UserMessagingPlatform.getConsentInformation(activity);
        ConsentRequestParameters params = new ConsentRequestParameters.Builder()
                .setTagForUnderAgeOfConsent(false)
                .build();
        consent.requestConsentInfoUpdate(activity, params,
                () -> UserMessagingPlatform.loadAndShowConsentFormIfRequired(activity, formError -> startIfAllowed()),
                requestError -> startIfAllowed());
        // consent obtained in a previous session: start right away
        startIfAllowed();
    }

    private void startIfAllowed() {
        if (!consent.canRequestAds() || !started.compareAndSet(false, true)) return;
        new Thread(() -> MobileAds.initialize(activity, status -> main.post(() -> {
            initialized = true;
            loadRewarded();
            loadInterstitial();
        }))).start();
    }

    private String id(String name) {
        int res = activity.getResources().getIdentifier(name, "string", activity.getPackageName());
        return res != 0 ? activity.getString(res) : "";
    }

    private void loadRewarded() {
        if (!initialized || rewarded != null || loadingRewarded) return;
        loadingRewarded = true;
        RewardedAd.load(activity, id("admob_rewarded_id"), new AdRequest.Builder().build(), new RewardedAdLoadCallback() {
            @Override
            public void onAdLoaded(@NonNull RewardedAd ad) {
                rewarded = ad;
                loadingRewarded = false;
                retryRewarded = 15_000;
            }

            @Override
            public void onAdFailedToLoad(@NonNull LoadAdError error) {
                rewarded = null;
                loadingRewarded = false;
                main.postDelayed(AdMobBackend.this::loadRewarded, retryRewarded);
                retryRewarded = Math.min(retryRewarded * 2, 300_000);
            }
        });
    }

    private void loadInterstitial() {
        if (!initialized || interstitial != null || loadingInterstitial) return;
        loadingInterstitial = true;
        InterstitialAd.load(activity, id("admob_interstitial_id"), new AdRequest.Builder().build(), new InterstitialAdLoadCallback() {
            @Override
            public void onAdLoaded(@NonNull InterstitialAd ad) {
                interstitial = ad;
                loadingInterstitial = false;
                retryInterstitial = 15_000;
            }

            @Override
            public void onAdFailedToLoad(@NonNull LoadAdError error) {
                interstitial = null;
                loadingInterstitial = false;
                main.postDelayed(AdMobBackend.this::loadInterstitial, retryInterstitial);
                retryInterstitial = Math.min(retryInterstitial * 2, 300_000);
            }
        });
    }

    @Override
    public boolean isAvailable() {
        return consent.canRequestAds();
    }

    @Override
    public boolean isReady(String kind) {
        return "rewarded".equals(kind) ? rewarded != null : interstitial != null;
    }

    @Override
    public void show(String kind, final String requestId) {
        if ("rewarded".equals(kind)) {
            final RewardedAd ad = rewarded;
            if (ad == null) {
                activity.adDone(requestId, false);
                loadRewarded();
                return;
            }
            rewarded = null;
            final boolean[] earned = {false};
            ad.setFullScreenContentCallback(new FullScreenContentCallback() {
                @Override
                public void onAdDismissedFullScreenContent() {
                    activity.adDone(requestId, earned[0]);
                    loadRewarded();
                }

                @Override
                public void onAdFailedToShowFullScreenContent(@NonNull AdError error) {
                    activity.adDone(requestId, false);
                    loadRewarded();
                }
            });
            ad.show(activity, reward -> earned[0] = true);
        } else {
            final InterstitialAd ad = interstitial;
            if (ad == null) {
                activity.adDone(requestId, false);
                loadInterstitial();
                return;
            }
            interstitial = null;
            ad.setFullScreenContentCallback(new FullScreenContentCallback() {
                @Override
                public void onAdDismissedFullScreenContent() {
                    activity.adDone(requestId, false);
                    loadInterstitial();
                }

                @Override
                public void onAdFailedToShowFullScreenContent(@NonNull AdError error) {
                    activity.adDone(requestId, false);
                    loadInterstitial();
                }
            });
            ad.show(activity);
        }
    }

    @Override
    public boolean privacyOptionsRequired() {
        return consent.getPrivacyOptionsRequirementStatus() == ConsentInformation.PrivacyOptionsRequirementStatus.REQUIRED;
    }

    @Override
    public void showPrivacyOptions() {
        UserMessagingPlatform.showPrivacyOptionsForm(activity, formError -> { });
    }
}
