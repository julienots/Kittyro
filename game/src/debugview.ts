// Temporary visual check harness (removed once the full game boots).
import * as THREE from 'three';
import { Renderer } from './render/Renderer';
import { SkyRig } from './render/Sky';
import { CameraRig } from './render/CameraRig';
import { Particles } from './render/Particles';
import { World } from './world/World';
import { Ctx } from './systems/Context';
import { createNewGame } from './state/newGame';
import { globalUniforms } from './render/Materials';
import { buildCharacter } from './models/Character';
import { buildAnimal } from './models/Animals';
import { updateGlow, updateWindows } from './world/PropFactory';

export function debugBoot(): void {
  const params = new URLSearchParams(location.search);
  const canvas = document.getElementById('game') as HTMLCanvasElement;
  canvas.style.cssText = 'position:fixed;inset:0;width:100%;height:100%';
  const r = new Renderer(canvas, (params.get('q') as any) ?? 'high');
  const st = createNewGame('Dev', 'Ferme', undefined, 42);
  const region = (params.get('r') ?? 'farm') as any;
  st.regions[region as 'farm'].unlocked = true;
  const day = Number(params.get('day') ?? 1);
  st.time.day = day;
  const ctx = new Ctx(st);
  const sky = new SkyRig();
  r.scene.add(sky.group);
  const parts = new Particles();
  r.scene.add(parts.group);
  const world = new World(ctx, parts, () => r.profile.grass, () => r.profile.lights);
  r.scene.add(world.root);
  let floor;
  if (region === 'mine') floor = ctx.mining.generate(Number(params.get('f') ?? 3));
  world.load(region, floor);
  sky.setShadowSize(r.profile.shadow);
  if (region === 'mine') sky.indoor = 'cave';
  if (region === 'house') sky.indoor = 'house';
  const rig = new CameraRig(r.camera);
  const fx = Number(params.get('x') ?? world.layout.anchors.spawn?.x ?? world.layout.w / 2);
  const fz = Number(params.get('z') ?? world.layout.anchors.spawn?.z ?? world.layout.d / 2);
  const p = new THREE.Vector3(fx, world.heightAt(fx, fz), fz);
  rig.snap(p);
  rig.zoomTarget = rig.zoom = Number(params.get('zoom') ?? 1);
  const ch = buildCharacter(st.player.look, { outline: true });
  ch.root.position.copy(p);
  r.scene.add(ch.root);
  const a = buildAnimal('cow', 0xffffff, 1, true);
  a.root.position.set(fx + 2, p.y, fz + 1);
  r.scene.add(a.root);
  const c = buildAnimal('chicken', 0xffffff, 0.55, true);
  c.root.position.set(fx - 1.5, p.y, fz + 1.5);
  r.scene.add(c.root);
  const minute = Number(params.get('m') ?? 600);
  let t = 0;
  const loop = () => {
    t += 1 / 60;
    globalUniforms.uTime.value = t;
    sky.update(minute, t, p, r.scene);
    updateGlow(sky.state.night);
    updateWindows(sky.state.night);
    rig.update(1 / 60, p, new THREE.Vector3());
    rig.updateSeeThrough(p);
    world.update(1 / 60, t, sky.state.night, p, r.camera);
    parts.update(1 / 60);
    r.render();
    (window as any).__frames = ((window as any).__frames ?? 0) + 1;
    (window as any).__info = r.info();
    requestAnimationFrame(loop);
  };
  loop();
  window.addEventListener('resize', () => r.resize());
}
